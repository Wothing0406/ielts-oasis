/* One release source, also works inside the frontend-only Docker build context. */
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),{version}=JSON.parse(fs.readFileSync(path.join(root,'meowcha-release.json'),'utf8'));
if(!/^\d+\.\d+$/.test(version))throw new Error('Invalid release');
const game=path.join(root,'public/meowcha'),html=path.join(game,'index.html');
fs.writeFileSync(html,fs.readFileSync(html,'utf8').replace(/([.]js|[.]css)\?v=[^"']+/g,'$1?v='+version));
const build={version,git_sha:process.env.MEOWCHA_GIT_SHA||'development',build_timestamp:process.env.MEOWCHA_BUILD_TIMESTAMP||'development'};
fs.writeFileSync(path.join(game,'js/core/Release.js'),`/* Generated by scripts/meowcha-release.cjs. */\nwindow.Meowcha=window.Meowcha||{};window.Meowcha.RELEASE=${JSON.stringify(version)};window.Meowcha.BUILD=${JSON.stringify(build)};\n`);
